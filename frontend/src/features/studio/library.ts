import type { Layer } from '@/lib/api/client'

export function newId(): string {
  return Math.random().toString(16).slice(2, 12)
}

export function newLayer(over: Partial<Layer> = {}): Layer {
  return {
    id: newId(),
    kind: 'text',
    role: 'user',
    name: '',
    visible: true,
    x: 0.5,
    y: 0.5,
    scale: 1,
    rotation: 0,
    opacity: 1,
    start: 0,
    end: null,
    anim_in: 'pop',
    anim_out: 'fade',
    loop: 'none',
    text: '',
    font: 'impact',
    size: 80,
    color: '#FFFFFF',
    stroke_color: '#000000',
    stroke: 6,
    shadow: true,
    italic: false,
    upper: true,
    max_width: 0.86,
    shape: 'none',
    shape_color: '#7C3AED',
    shape_stroke: null,
    asset_id: null,
    width: 0.25,
    ...over,
  }
}

